import { readFile, writeFile } from 'node:fs/promises';
import { fileURLToPath } from 'node:url';
import path from 'node:path';
const root = path.dirname(fileURLToPath(import.meta.url));
const read = file => readFile(path.join(root, file), 'utf8');
const manifest = JSON.parse(await read('package.json'));
const [model, ui, css, en, zh] = await Promise.all([
  read('src/model.js'), read('src/ui.js'), read('src/style.css'), read('locale/en.json'), read('locale/zh.json'),
]);
const source = text => text.replace(/^import .* from '\.\/model\.js';\r?\n/m, '').replace(/^export (?=(?:async )?function |const )/gm, '');
const enUi = JSON.parse(en).ui;
const zhUi = JSON.parse(zh).ui;
const result = `/* Generated by build.mjs. React is supplied by DSH; no external runtime dependencies. */
window.__ModuleLoader__.load({
  id: ${JSON.stringify(manifest.name)},
  factory(require) {
    'use strict';
    const React = require('react');
    const CSS = ${JSON.stringify(css)};
    const EN = ${JSON.stringify(enUi)};
    const ZH = ${JSON.stringify(zhUi)};
    const NS = 'simonwicreSessionView';
    const PANEL = 'simonwicre-session-view';
${source(model)}
${source(ui)}
    const { SessionOverview, PanelIcon } = createUi(React);
    function Page(props) {
      return React.createElement(React.Fragment, null,
        React.createElement('style', null, CSS), React.createElement(SessionOverview, props));
    }
    return {
      inject: ['slots', 'locale', 'layout', 'sessions', 'uiWorkspace'],
      apply(ctx) {
        ctx.locale.register(NS, 'en', EN);
        ctx.locale.register(NS, 'zh', ZH);
        const t = ctx.locale.bind(NS);
        const face = {
          searchContent: (query, signal) => ctx.sessions.search(query, signal),
          refreshList: async () => {
            await ctx.sessions.refresh();
            if (ctx.sessions.list.getSnapshot().phase !== 'ready') throw new Error('Session catalog unavailable');
          },
          openSession: id => ctx.uiWorkspace.openSession(id),
          returnToChat: () => ctx.layout.selectPanel(null),
          getLanguage: () => ctx.locale.getLocale().active,
          searchResultLimit: ctx.sessions.searchResultLimit,
        };
        ctx.slots.inject('main', () => ctx.slots.register({
          name: 'main', key: PANEL, locale: NS, inject: () => face,
        }, Page));
        ctx.slots.inject('sidebar.panellist', () => ctx.slots.register({
          name: 'sidebar.panellist', id: PANEL, order: 15, label: () => t('panel'), locale: NS,
        }, PanelIcon));
      },
    };
  },
});
`;
await writeFile(path.join(root, 'client.js'), result, 'utf8');
console.log(`Built ${manifest.name}@${manifest.version}: ${Buffer.byteLength(result)} bytes`);
